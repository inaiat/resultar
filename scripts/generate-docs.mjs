import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(join(root, "packages/resultar/package.json"));
const ts = require("typescript/unstable/sync");
const { SyntaxKind } = require("typescript/unstable/ast");
const check = process.argv.includes("--check");
const packages = readdirSync(join(root, "packages"))
  .sort()
  .map((directory) => {
    const metadata = JSON.parse(
      readFileSync(join(root, "packages", directory, "package.json"), "utf8"),
    );
    return { directory, ...metadata };
  })
  .filter((pkg) => pkg.types);
const files = packages.map((pkg) => join(root, "packages", pkg.directory, pkg.types));
const directory = mkdtempSync(join(tmpdir(), "resultar-docs-"));
const config = join(directory, "tsconfig.json");
writeFileSync(
  config,
  JSON.stringify({
    files,
    compilerOptions: {
      target: "ESNext",
      module: "NodeNext",
      skipLibCheck: true,
    },
  }),
);
const api = new ts.API({ cwd: root });
try {
  const snapshot = api.updateSnapshot({ openProjects: [config] });
  const { program, checker } = snapshot.getProject(config);

  function publicMembers(type) {
    return checker
      .getPropertiesOfType(type)
      .filter(
        (symbol) =>
          symbol.name !== "prototype" &&
          !symbol.name.startsWith("__@") &&
          !(symbol.declarations ?? []).some(
            (declaration) =>
              declaration.resolve()?.name?.kind === SyntaxKind.PrivateIdentifier ||
              declaration
                .resolve()
                ?.modifiers?.some(
                  (modifier) =>
                    modifier.kind === SyntaxKind.PrivateKeyword ||
                    modifier.kind === SyntaxKind.ProtectedKeyword,
                ),
          ),
      )
      .map((symbol) => `\`${symbol.name}\``)
      .sort()
      .join(", ");
  }

  let inventory = `# Public API inventory

Generated by \`vp run docs:generate\` from built public declarations. Do not edit
this file by hand. \`vp run test:docs\` checks for drift after the build.
This is a discovery index, not an overload specification: installed declarations
remain authoritative for signatures, generics, overloads, and member deprecations.
See the [full guide](../DOCUMENTATION.md) for behavior and executable examples.
All exported types are listed, including compatibility types. Static/value and
instance members are distinguished; symbol protocol members (iteration/disposal)
are described in the declarations. A deprecated export remains supported.

The [native checker](../packages/check/README.md) exposes CLI/LSP commands and
[configuration schema](../packages/check/schema.json), not a JavaScript API.

`;
  for (const [index, pkg] of packages.entries()) {
    const source = program.getSourceFile(files[index]);
    assert.ok(source, `Build ${pkg.name} before generating documentation`);
    const module = checker.getSymbolAtLocation(source);
    assert.ok(module, `Missing declaration module for ${pkg.name}`);
    inventory += `## ${pkg.name}\n\n[Package manual](../packages/${pkg.directory}/README.md)\n\n`;
    inventory += "| Export | Kind | Public members |\n| --- | --- | --- |\n";
    for (const exported of [...checker.getExportsOfModule(module)].sort((a, b) =>
      a.name.localeCompare(b.name),
    )) {
      const symbol =
        exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
      const declaration = symbol.valueDeclaration ?? symbol.declarations?.[0];
      const value = Boolean(symbol.flags & ts.SymbolFlags.Value);
      const isClass = Boolean(symbol.flags & ts.SymbolFlags.Class);
      const deprecated = symbol.getJsDocTags(checker).some((tag) => tag.name === "deprecated");
      let members = "";
      if (value && declaration) members = publicMembers(checker.getTypeOfSymbol(symbol));
      if (isClass) {
        const instance = publicMembers(checker.getDeclaredTypeOfSymbol(symbol));
        members = [members && `Static: ${members}`, instance && `Instance: ${instance}`]
          .filter(Boolean)
          .join("<br>");
      } else if (!value && symbol.flags & ts.SymbolFlags.Interface) {
        members = publicMembers(checker.getDeclaredTypeOfSymbol(symbol));
      }
      inventory += `| \`${exported.name}\` | ${isClass ? "Class" : value ? "Value" : "Type"}${deprecated ? " (deprecated)" : ""} | ${members || "—"} |\n`;
    }
    inventory += "\n";
  }

  const recipes = `# Executable contract recipes

These examples are the published source of the bundled agent recipes. They use
only core Resultar and Node.js, without network access. \`vp run test:docs\` verifies
this page matches the source, compiles the published recipes, and tests their
observable behavior. Partial snippets elsewhere in the manuals require the
surrounding application types; this page is a complete module.

The recipes distinguish external Promise driver inputs (\`lazyLoad\` uses
\`tryPromise\`) from existing typed Async adapters (\`bridgeExistingLoad\` uses
\`fromResultAsync\`). Both return Tasks without \`async\`. \`runDefectInspection\`
is an explicit runner boundary returning a native Promise, not a repository method.
See [Promise boundaries](../DOCUMENTATION.md#promise-boundaries-and-application-contracts).

They also demonstrate numeric retry policies,
synchronous Result steps in Tasks, scope release and native disposal, semaphores,
callback cancellation/cleanup, tagged enums, matching, redaction, fallbacks,
first-success versus first-completion racing, and defect inspection via Exit.
See the [workflow example](../skills/resultar/examples/workflow.mts) for service
requirements supplied at the runner. Framework and schema integrations are
exercised by [example projects](../README.md#runnable-examples) and agent evaluation cases.

Source: [contracts.mts](../skills/resultar/examples/contracts.mts).

\`\`\`ts
${readFileSync(join(root, "skills/resultar/examples/contracts.mts"), "utf8").trimEnd()}
\`\`\`
`;
  for (const [name, content] of [
    ["docs/api-inventory.md", `${inventory.trimEnd()}\n`],
    ["docs/recipes.md", recipes],
  ]) {
    const path = join(root, name);
    if (check)
      assert.equal(
        readFileSync(path, "utf8"),
        content,
        `${name} is stale; build, then run vp run docs:generate`,
      );
    else writeFileSync(path, content);
  }
  console.log(`${check ? "Verified" : "Generated"} public API inventory and executable recipes.`);
} finally {
  api.close();
  rmSync(directory, { recursive: true, force: true });
}
